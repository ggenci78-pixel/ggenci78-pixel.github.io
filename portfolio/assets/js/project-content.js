import { evidence } from './imported-evidence.js';

const pages = (...numbers) => numbers.flatMap(n => evidence.pages[n] || []);
const chapter = (title, text, numbers, caption, indices) => {
  const files = pages(...numbers);
  return {title, text, figures:(indices ? indices.map(i=>files[i]) : files).map((file,i)=>({file,caption:`${caption} / ${String(i+1).padStart(2,'0')}`}))};
};
const sourceNote = '图片保留原始像素；矢量与组合版面按 PDF 源页渲染。部分早期位图在 PDF 中已经压缩，细节受原稿限制。';
const visual = (id, title, subtitle, en, type, displayLines, chapters, sourcePage, role) => ({
  id, collection: 'visual', title, subtitle, en, type, displayLines, chapters,
  cover: chapters.flatMap(c => c.figures)[0].file,
  images: chapters.flatMap(c => c.figures).slice(1).map(f => f.file),
  description: chapters[0].text, sections: chapters.map(c => c.title),
  body: chapters.map(({title, text}) => ({title, text})),
  status: role, qualityNote: sourceNote,
});

